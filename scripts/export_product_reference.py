"""
Exports the product spoilage reference as a readable sheet for the simulator developer.

Usage (from the repo root):
    python scripts/export_product_reference.py
"""

from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[1]
CSV = REPO_ROOT / "data" / "reference" / "product_spoilage_reference.csv"
OUT = REPO_ROOT / "docs" / "dataset" / "product_reference_for_simulator.md"


def md_table(frame):
    cols = list(frame.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, row in frame.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


def main():
    df = pd.read_csv(CSV, encoding="utf-8-sig")
    names = df[["product_name"]].copy()
    names["form_used_in_dbt"] = names["product_name"].str.strip().str.lower()
    names = names.rename(columns={"product_name": "exact_spelling_in_csv"})

    thresholds = df[["product_name", "product_stage_or_variety", "recommended_temp_min_c",
                     "recommended_temp_max_c", "best_temp_c", "humidity_min_pct", "humidity_max_pct",
                     "shelf_life_min_hours", "shelf_life_max_hours", "data_source"]]

    zero_width = df[df["recommended_temp_min_c"] == df["recommended_temp_max_c"]]["product_name"].tolist()

    columns = pd.DataFrame([
        ("product_name", "STRING", "none", "Product name, unique with the stage"),
        ("product_stage_or_variety", "STRING", "none", "Stage or variety the thresholds apply to"),
        ("recommended_temp_min_c", "FLOAT", "degrees C", "Lower end of the recommended temperature"),
        ("recommended_temp_max_c", "FLOAT", "degrees C", "Upper end of the recommended temperature"),
        ("best_temp_c", "FLOAT", "degrees C", "Reference temperature, inside the range"),
        ("humidity_min_pct", "FLOAT", "percent", "Lower end of the recommended relative humidity"),
        ("humidity_max_pct", "FLOAT", "percent", "Upper end of the recommended relative humidity"),
        ("shelf_life_min_hours", "FLOAT", "hours", "Shorter storage life estimate"),
        ("shelf_life_max_hours", "FLOAT", "hours", "Longer storage life estimate"),
        ("data_source", "STRING", "none", "Origin of the thresholds"),
        ("source_url", "STRING", "none", "Reference link"),
        ("notes", "STRING", "none", "Free text"),
    ], columns=["column", "type", "unit", "meaning"])

    text = [
        "# Product Reference for the Simulator (generated from data/reference/product_spoilage_reference.csv)",
        "",
        f"Products: {len(df)}. Generated by scripts/export_product_reference.py. All values are reference values from the CSV; unverified thresholds are prototype assumptions.",
        "",
        "## 1. Exact product names",
        "The container metadata must use the spelling in the first column. dbt lowercases and trims names before joining.",
        md_table(names),
        "",
        "## 2. Thresholds",
        md_table(thresholds),
        "",
        "## 3. CSV columns and types",
        md_table(columns),
        "",
        "## 4. Risk rules (proposal, awaiting the coordinator's approval)",
        "- A temperature excursion is a reading below recommended_temp_min_c or above recommended_temp_max_c of the container's product. Humidity works the same with humidity_min_pct and humidity_max_pct.",
        "- Time between two readings counts as excursion time only up to 15 seconds (three times the expected 5-second interval), so a data gap is never counted as excursion time.",
        "- Risk level by the share of observed time outside the range: low below 5 percent, medium 5 to 20 percent, high above 20 percent. This is a prototype rating, not a food-safety rating.",
        f"- Products with a zero-width temperature range (min equals max): {', '.join(zero_width) if zero_width else 'none'}. Any reading with noise lies outside such a range, so the rule needs a tolerance (proposal for discussion: the sensor uncertainty of 0.5 C).",
        "",
        "## 5. Container metadata requirements (separate reference dataset keyed by container_id)",
        "Suggested file: data/reference/container_metadata.csv, comma-separated, UTF-8, one row per container.",
        md_table(pd.DataFrame([
            ("container_id", "STRING", "required, unique, same IDs as the telemetry (CONT001 to CONT005)"),
            ("product_name", "STRING", "required, exactly one of the names in section 1"),
            ("quantity", "FLOAT", "required, greater than 0"),
            ("quantity_unit", "STRING", "required, for example kg"),
            ("origin", "STRING", "required"),
            ("destination", "STRING", "required"),
            ("batch_id", "STRING", "required"),
            ("source_type", "STRING", "required, synthetic_simulated for simulator-made rows"),
        ], columns=["column", "type", "rule"])),
        "",
        "## 6. Suggestions for the simulator scenarios",
        "- Keep the nine-field telemetry event unchanged.",
        "- Generate temperature and humidity around best_temp_c and the humidity range of the container's product, read from the CSV, not hard-coded.",
        "- Scenarios: normal (inside the range), short excursion (a few minutes above the maximum), prolonged excursion (hours above the maximum), recovery. Any drift or fault option should default to off.",
        "- Mark all generated telemetry with source_type = synthetic_simulated.",
    ]
    OUT.write_text("\n".join(text) + "\n", encoding="utf-8")
    print(f"Wrote {OUT} ({len(df)} products, zero-width temperature range: {zero_width})")


if __name__ == "__main__":
    main()