USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ATMOSYNC_WH;

CREATE SCHEMA IF NOT EXISTS ATMOSYNC.INTERMEDIATE;
GRANT USAGE ON SCHEMA ATMOSYNC.INTERMEDIATE TO ROLE ATMOSYNC_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ATMOSYNC.INTERMEDIATE TO ROLE ATMOSYNC_READER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA ATMOSYNC.INTERMEDIATE TO ROLE ATMOSYNC_READER;

USE SCHEMA ATMOSYNC.RAW;

CREATE TABLE IF NOT EXISTS RAW_COMMODITY_PRICE_MONTHLY (
  PRICE_MONTH DATE,
  COMMODITY   STRING,
  UNIT        STRING,
  PRICE       FLOAT,
  SOURCE_FILE STRING,
  LOADED_AT   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS RAW_HOUSEHOLD_FRIDGE_READINGS (
  FRIDGE_NUMBER NUMBER,
  FRIDGE_TYPE   STRING,
  TIME_MINUTES  FLOAT,
  T_AMB  FLOAT,
  T_MS   FLOAT,
  T_TS   FLOAT,
  T_VD   FLOAT,
  T_DS   FLOAT,
  T_FC   FLOAT,
  RH_AMB FLOAT,
  RH_MS  FLOAT,
  RH_TS  FLOAT,
  RH_VD  FLOAT,
  RH_DS  FLOAT,
  RH_FC  FLOAT,
  TP     FLOAT,
  SOURCE_FILE STRING,
  LOADED_AT   TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Loaders reload these tables in full, so they need DELETE as well
GRANT SELECT, INSERT, DELETE ON TABLE ATMOSYNC.RAW.RAW_COMMODITY_PRICE_MONTHLY TO ROLE ATMOSYNC_LOADER;
GRANT SELECT, INSERT, DELETE ON TABLE ATMOSYNC.RAW.RAW_HOUSEHOLD_FRIDGE_READINGS TO ROLE ATMOSYNC_LOADER;

SHOW TABLES IN SCHEMA ATMOSYNC.RAW;